"""Hooks component — script copies + per-tool settings merge.

A hook is two things: a shell script run on a coding-tool event (Stop,
UserPromptSubmit, PreToolUse, …), and a binding in the tool's settings file
declaring the event/matcher/command combination. Authors edit both in one
place under `platform/hooks/<repo>/`:

    platform/hooks/<repo>/
      hooks.yaml             — event bindings (one entry per hook)
      scripts/*.sh           — the actual scripts

All three of Claude Code, Cursor, and Factory droid support hooks today
(Cursor since v1.0, droid since v0.21+, Claude since 1.0.0). The schemas
diverge in three ways:

* **Settings file** — Claude: `.claude/settings.json`, Cursor:
  `.cursor/hooks.json` (dedicated file), droid: `.factory/settings.json`.
* **Per-binding shape** — Claude and droid nest bindings under
  `{matcher, hooks: [{type, command}]}`; Cursor flattens to
  `{command, type, matcher}` at the event level.
* **Event names** — Claude and droid use PascalCase (`Stop`,
  `UserPromptSubmit`); Cursor uses camelCase and renames a few (`stop`,
  `beforeSubmitPrompt`). A small per-tool translation table absorbs this.
* **Top-level wrapper** — Cursor's `hooks.json` carries `{"version": 1,
  "hooks": {…}}`; Claude/droid have no such field.

The engine writes scripts to `<repo>/<hooks_dir>/_org/<name>.sh` (engine
namespace per tool — e.g. `.claude/hooks/_org/`, `.cursor/hooks/_org/`,
`.factory/hooks/_org/`) and merges bindings into the per-tool settings file.
Only entries whose command path starts with `<hooks_dir>/_org/` are
considered engine-managed; user-authored hooks elsewhere are preserved.

`hooks.yaml` schema (canonical, tool-agnostic):

    hooks:
      - event: Stop                          # canonical PascalCase event name
        matcher: ""                          # optional, defaults to ""
        script: check-platform-drift.sh      # filename in scripts/
        tools: [claude, cursor, droid]       # optional; defaults to all 3
"""

from __future__ import annotations

import json
import stat
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

# Where engine-managed scripts land inside each per-tool hooks_dir. Anything
# outside this subdir is treated as user-authored and never touched by the merger.
ENGINE_NAMESPACE = "_org"

# Tag we put on each engine-managed settings hook entry. Lets the merger
# identify and replace only entries we own, even after the user reorders
# the `hooks` block by hand. Same key in all three tools' schemas.
_MANAGED_KEY = "__org_managed__"

# Translate canonical PascalCase event names to each tool's native form. Tools
# absent from this map use the canonical name verbatim. Add an entry only when
# a tool actually renames the event (Cursor renames a couple).
_EVENT_TRANSLATIONS: dict[str, dict[str, str]] = {
    "cursor": {
        "Stop": "stop",
        "UserPromptSubmit": "beforeSubmitPrompt",
        "PreToolUse": "preToolUse",
        "PostToolUse": "postToolUse",
        "SessionStart": "sessionStart",
        "SessionEnd": "sessionEnd",
        "SubagentStop": "subagentStop",
        "PreCompact": "preCompact",
    },
}

# Tools that use the flat per-binding schema (`{command, type, matcher}`)
# instead of the nested form (`{matcher, hooks: [{type, command}]}`).
_FLAT_SCHEMA_TOOLS = {"cursor"}

_SCRIPT_MARKER = (
    "# Generated by `org install` from {source} — edit the source, not this file.\n"
)


@dataclass(frozen=True)
class HookBinding:
    event: str            # canonical PascalCase event name
    matcher: str
    script: str           # script filename (basename only); resolved against scripts/
    tools: tuple[str, ...]  # which tools this binding applies to
    source_rel: str       # workspace-relative path to the hooks.yaml entry


@dataclass(frozen=True)
class HookSource:
    """A platform hook source: bindings + scripts."""

    bindings: tuple[HookBinding, ...] = field(default_factory=tuple)
    scripts: tuple[Path, ...] = field(default_factory=tuple)

    @property
    def is_empty(self) -> bool:
        return not self.bindings and not self.scripts


def load_source(plat: Path, repo: str, root: Path) -> HookSource:
    """Read `platform/hooks/<repo>/{hooks.yaml, scripts/*.sh}` into a HookSource."""
    hooks_dir = plat / "hooks" / repo
    if not hooks_dir.is_dir():
        return HookSource()

    bindings: list[HookBinding] = []
    hooks_yaml = hooks_dir / "hooks.yaml"
    if hooks_yaml.is_file():
        raw = yaml.safe_load(hooks_yaml.read_text(encoding="utf-8")) or {}
        source_rel = hooks_yaml.relative_to(root).as_posix()
        for entry in raw.get("hooks") or []:
            tools_field = entry.get("tools")
            tools_tuple = tuple(tools_field) if tools_field else ("claude", "cursor", "droid")
            bindings.append(
                HookBinding(
                    event=str(entry["event"]),
                    matcher=str(entry.get("matcher", "")),
                    script=str(entry["script"]),
                    tools=tools_tuple,
                    source_rel=source_rel,
                )
            )

    scripts_dir = hooks_dir / "scripts"
    scripts = tuple(sorted(scripts_dir.glob("*.sh"))) if scripts_dir.is_dir() else ()

    return HookSource(bindings=tuple(bindings), scripts=scripts)


def render_script(source_text: str, source_rel: str) -> str:
    """Inject the generated-by marker after the shebang line (if any)."""
    marker = _SCRIPT_MARKER.format(source=source_rel)
    if source_text.startswith("#!"):
        first_newline = source_text.find("\n")
        if first_newline == -1:
            return source_text + "\n" + marker
        return source_text[: first_newline + 1] + marker + source_text[first_newline + 1 :]
    return marker + source_text


def _event_for(tool: str, canonical: str) -> str:
    return _EVENT_TRANSLATIONS.get(tool, {}).get(canonical, canonical)


def _binding_entry(tool: str, command: str, matcher: str) -> dict[str, Any]:
    """Render one binding in the tool's native shape."""
    if tool in _FLAT_SCHEMA_TOOLS:
        # Cursor flat: {command, type, matcher, __org_managed__}
        out: dict[str, Any] = {"command": command, "type": "command"}
        if matcher:
            out["matcher"] = matcher
        out[_MANAGED_KEY] = True
        return out
    # Claude / droid nested: caller wraps these inside {matcher, hooks: [...]}
    return {"type": "command", "command": command, _MANAGED_KEY: True}


_PROJECT_DIR_VARS = {
    "claude": "$CLAUDE_PROJECT_DIR",
    "cursor": "$CURSOR_PROJECT_DIR",
    "droid": "$FACTORY_PROJECT_DIR",
}


def _command_path(tool: str, hooks_dir: str, script: str, global_root: str | None) -> str:
    """Resolve the on-disk command path for one hook script.

    Per-repo (`global_root` is None): `$<TOOL>_PROJECT_DIR/<hooks_dir>/_org/<script>`
    — the project dir var expands to the active repo at runtime.

    User-global (`global_root` set): `<global_root>/_org/<script>` — an absolute
    path under $HOME, because the script doesn't live inside the active project.
    """
    if global_root is not None:
        return f"{global_root}/{ENGINE_NAMESPACE}/{script}"
    return f"{_PROJECT_DIR_VARS[tool]}/{hooks_dir}/{ENGINE_NAMESPACE}/{script}"


def build_managed_block(
    bindings: list[HookBinding],
    tool: str,
    hooks_dir: str,
    global_root: str | None = None,
) -> dict[str, Any]:
    """Build the per-tool managed `hooks` dict for one tool.

    `hooks_dir` is the per-tool destination (e.g. `.claude/hooks`); the engine
    namespace `_org/` is appended for the command path. When `global_root` is
    given (user-global install), the command path is absolute under $HOME and
    `hooks_dir` is ignored — see `_command_path`.
    """
    # Filter to bindings that target this tool.
    own = [b for b in bindings if tool in b.tools]
    if not own:
        return {}

    out: dict[str, Any] = {}
    if tool in _FLAT_SCHEMA_TOOLS:
        # Cursor: each event maps directly to a list of flat binding entries.
        for b in own:
            event = _event_for(tool, b.event)
            command = _command_path(tool, hooks_dir, b.script, global_root)
            out.setdefault(event, []).append(_binding_entry(tool, command, b.matcher))
        return out

    # Claude / droid nested form: group by event, then by matcher.
    by_event: dict[str, dict[str, list[dict[str, Any]]]] = {}
    for b in own:
        event = _event_for(tool, b.event)
        command = _command_path(tool, hooks_dir, b.script, global_root)
        by_matcher = by_event.setdefault(event, {})
        by_matcher.setdefault(b.matcher, []).append(_binding_entry(tool, command, b.matcher))
    for event, by_matcher in by_event.items():
        out[event] = [{"matcher": matcher, "hooks": hooks} for matcher, hooks in by_matcher.items()]
    return out


def _strip_managed_nested(event_blocks: Any) -> list[dict[str, Any]]:
    """Strip engine-managed entries from a Claude/droid-style event block."""
    if not isinstance(event_blocks, list):
        return []
    kept: list[dict[str, Any]] = []
    for block in event_blocks:
        if not isinstance(block, dict):
            continue
        hooks = block.get("hooks")
        if not isinstance(hooks, list):
            continue
        user_hooks = [h for h in hooks if not (isinstance(h, dict) and h.get(_MANAGED_KEY))]
        if user_hooks:
            new_block = dict(block)
            new_block["hooks"] = user_hooks
            kept.append(new_block)
    return kept


def _strip_managed_flat(event_blocks: Any) -> list[dict[str, Any]]:
    """Strip engine-managed entries from a Cursor-style event block."""
    if not isinstance(event_blocks, list):
        return []
    return [
        entry
        for entry in event_blocks
        if isinstance(entry, dict) and not entry.get(_MANAGED_KEY)
    ]


def merge_into_settings(
    settings: dict[str, Any],
    managed: dict[str, Any],
    tool: str,
) -> dict[str, Any]:
    """Return a copy of `settings` with engine-managed `hooks` replaced by `managed`.

    User-authored entries (no `__org_managed__: true`) are preserved alongside.
    Empty event lists are pruned; an empty `hooks` block is pruned entirely.
    """
    result = dict(settings)
    existing = result.get("hooks") or {}
    if not isinstance(existing, dict):
        existing = {}

    strip = _strip_managed_flat if tool in _FLAT_SCHEMA_TOOLS else _strip_managed_nested

    user_only: dict[str, list[dict[str, Any]]] = {}
    for event, blocks in existing.items():
        kept = strip(blocks)
        if kept:
            user_only[event] = kept

    # Deterministic iteration order: every event the user has, in their order,
    # then every managed event not already seen, in managed insertion order.
    # `set | set` would non-deterministically reorder and produce phantom DRIFT
    # on the next --check.
    merged: dict[str, list[dict[str, Any]]] = {}
    seen: set[str] = set()
    for event in user_only:
        merged[event] = list(user_only[event]) + list(managed.get(event, []))
        seen.add(event)
    for event in managed:
        if event in seen:
            continue
        merged[event] = list(managed[event])

    if merged:
        result["hooks"] = merged
    elif "hooks" in result:
        del result["hooks"]
    return result


def settings_template(tool: str) -> dict[str, Any]:
    """Per-tool top-level fields that should be present even in a fresh settings file."""
    if tool in _FLAT_SCHEMA_TOOLS:
        # Cursor hooks.json carries a version field at the top level.
        return {"version": 1}
    return {}


def write_executable(path: Path, content: str) -> None:
    """Write `content` to `path` and chmod it user-rwx + group/other-rx."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    current = path.stat().st_mode
    path.chmod(current | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def render_settings(settings: dict[str, Any]) -> str:
    """Serialize merged settings deterministically (2-space indent + trailing newline)."""
    return json.dumps(settings, indent=2, ensure_ascii=False) + "\n"


def read_settings(settings_path: Path) -> dict[str, Any]:
    """Read settings safely. Missing file or non-dict content → empty dict."""
    if not settings_path.is_file():
        return {}
    try:
        data = json.loads(settings_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return {}
    return data if isinstance(data, dict) else {}
