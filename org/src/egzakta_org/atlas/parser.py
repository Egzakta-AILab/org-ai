"""Parse atlas markdown files into Node objects.

Tolerance philosophy: drafts and half-finished files happen. The loader emits
warnings (via the logger) for unparseable files and skips them rather than
raising. Strict checks live in `validate.py` and surface through
`org atlas validate`.
"""

from __future__ import annotations

import logging
import re
from pathlib import Path
from typing import Any

import yaml

from ..workspace import find_workspace_root
from .model import AtlasIndex, Node

# Folders under atlas/ that hold one-node-per-markdown content. Everything else
# in atlas/ is intentionally excluded:
#   refs/      — free-form indexes (no frontmatter id); think of these as views
#   research/  — long-form research docs; frontmatter optional and inconsistent
#   items/     — autogenerated browser pages (gitignored)
#   scripts/   — Python helpers (gitignored, pending port)
NODE_DIRS: tuple[str, ...] = (
    "pillars",
    "platform",
    "capabilities",
    "ops",
    "experience",
    "commercial",
    "keystones",
    "personas",
    "milestones",
)

# `---\n<yaml>\n---\n<body>`. DOTALL so multiline yaml/body are captured.
_FRONTMATTER_RE = re.compile(r"^---\n(.*?)\n---\n?(.*)$", re.DOTALL)

logger = logging.getLogger(__name__)


class AtlasError(Exception):
    """Raised for unrecoverable atlas problems (missing root, etc.)."""


def split_frontmatter(text: str) -> tuple[str | None, str]:
    """Split ``---yaml---\\nbody`` into ``(yaml_text, body)``. Returns ``(None, text)``
    if no frontmatter block is present.
    """
    match = _FRONTMATTER_RE.match(text)
    if not match:
        return None, text
    return match.group(1), match.group(2)


def parse_node(path: Path, atlas_root: Path, workspace_root: Path) -> Node | None:
    """Parse one markdown file into a Node. Returns None (with a warning) on failure.

    Files without frontmatter, with non-dict frontmatter, or missing an ``id``
    are skipped with a log message. They surface as errors in `validate`.
    """
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        logger.warning("atlas: cannot read %s (%s)", path, exc)
        return None

    yaml_text, body = split_frontmatter(text)
    if yaml_text is None:
        logger.warning("atlas: %s has no frontmatter; skipping", path)
        return None

    try:
        raw: Any = yaml.safe_load(yaml_text)
    except yaml.YAMLError as exc:
        logger.warning("atlas: %s frontmatter is not valid YAML (%s)", path, exc)
        return None

    if not isinstance(raw, dict):
        logger.warning("atlas: %s frontmatter is not a mapping; skipping", path)
        return None

    node_id = raw.get("id")
    if not isinstance(node_id, str) or not node_id.strip():
        logger.warning("atlas: %s missing `id:` field; skipping", path)
        return None

    name = raw.get("name") or path.stem
    type_ = raw.get("type") or path.parent.name.rstrip("s")  # `capabilities` → `capability`

    try:
        rel = path.relative_to(workspace_root).as_posix()
    except ValueError:
        # Atlas might live outside the workspace in tests; fall back to atlas-relative.
        rel = path.relative_to(atlas_root.parent).as_posix() if atlas_root else str(path)

    return Node(
        id=node_id.strip(),
        name=str(name),
        type=str(type_),
        path=path,
        rel_path=rel,
        frontmatter=raw,
        body=body,
    )


def load_atlas(root: Path | None = None) -> AtlasIndex:
    """Walk `atlas/` and parse every node markdown into an AtlasIndex.

    `root` defaults to ``<workspace_root>/atlas``. Raises AtlasError if the
    atlas directory does not exist.
    """
    workspace_root = find_workspace_root()
    atlas_root = (root or workspace_root / "atlas").resolve()
    if not atlas_root.is_dir():
        raise AtlasError(f"atlas directory not found at {atlas_root}")

    nodes: list[Node] = []
    for dir_name in NODE_DIRS:
        dir_path = atlas_root / dir_name
        if not dir_path.is_dir():
            continue
        for md_path in sorted(dir_path.glob("*.md")):
            node = parse_node(md_path, atlas_root, workspace_root)
            if node is not None:
                nodes.append(node)

    by_id: dict[str, Node] = {}
    for node in nodes:
        # Duplicate ids are kept (first wins for lookup) and surfaced by validate.
        by_id.setdefault(node.id, node)

    return AtlasIndex(root=atlas_root, nodes=tuple(nodes), by_id=by_id)
