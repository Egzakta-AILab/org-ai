"""Skills component — directory-sync, not file render.

A `skill` is a directory of files (a `SKILL.md` plus optional scripts/docs/deps).
The registry at `platform/skills/index.yaml` declares each skill's mode and source:

* `reference` (the default and only supported mode today) — the skill lives upstream;
  the engine `git clone`s it pinned to `ref` directly into the destination. For repos
  that nest the skill under a sub-path, the engine clones once into a shared cache
  under ~/.cache/egzakta-org/skills/, then copies the sub-path into each destination.
* `vendor` — for skills we author under `platform/skills/vendor/<name>/`. The
  engine copies the directory into the destination (skipping `.git`,
  `node_modules`, `.env*`) and records a content hash of the source in the
  install stamp so drift detection picks up any platform-side edits.

Idempotency: every managed destination carries an `.org-install-stamp` file holding
the resolved upstream commit, the requested ref, and a fingerprint of `post_install`.
`org install --check` reports DRIFT if the stamp is stale or missing, the wrong ref
is checked out, or there are uncommitted local edits in the dest.

Secrets are never read or copied by the engine. `secrets_env` is documentation
surfaced in the install output so the user knows which env vars to set.
"""

from __future__ import annotations

import hashlib
import os
import shlex
import shutil
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

import yaml
from rich.console import Console

from .render import render_tool_blocks

# Directories that must never be copied between skill installations: SCM state,
# language deps that should be regenerated by post_install, and local secrets.
_EXCLUDE = (".git", "node_modules", ".env", ".env.local")

_STAMP_NAME = ".org-install-stamp"

# When a skill has `patches:`, the engine resets a local branch of this name on top
# of the pinned ref and commits each applied patch onto it. Lets `git status` stay
# clean and gives drift detection a fixed anchor to validate against.
_MANAGED_BRANCH = "org-managed"

# Author metadata used when the engine commits applied patches; never leaks beyond
# the per-user skills clone.
_COMMIT_USER = "org-install"
_COMMIT_EMAIL = "org-install@local"

# Force LF on clone so our LF patches apply on Windows (global core.autocrlf=true).
_LF_CLONE_CONFIG = ["-c", "core.autocrlf=false", "-c", "core.eol=lf"]


@dataclass(frozen=True)
class SkillEntry:
    name: str
    mode: str
    tools: tuple[str, ...]
    source: str | None = None
    ref: str | None = None
    sub_path: str | None = None
    layout: str | None = None  # "multi" → repo contains skills/<name>/, install each
    post_install: tuple[str, ...] = ()
    secrets_env: tuple[str, ...] = ()
    # Patches are .patch files (git diff output) applied on top of the pinned ref.
    # Paths are relative to `platform/skills/patches/`. The engine creates a local
    # `org-managed` branch on top of the ref, applies each patch in order via
    # `git apply --index`, and commits the result so `git status` stays clean and
    # drift detection keeps working. Only direct-clone reference mode supports
    # patches today (sub-path skills are content copies, not git clones).
    patches: tuple[str, ...] = ()


@dataclass
class SkillAction:
    """One skill × one tool × one scope = one destination directory."""

    skill: str
    tool: str
    scope: str  # "global" or "project"
    dest: Path
    entry: SkillEntry
    repo: str | None = None  # set when scope == "project"


@dataclass
class SkillResult:
    """Outcome of processing a SkillAction."""

    status: str  # OK | INSTALLED | MISSING | DRIFT | WOULD | ERROR
    detail: str
    secrets: tuple[str, ...] = field(default_factory=tuple)


def load_registry(plat: Path) -> dict[str, SkillEntry]:
    """Load `platform/skills/index.yaml` into a name → SkillEntry mapping."""
    path = plat / "skills" / "index.yaml"
    if not path.is_file():
        return {}
    raw = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    out: dict[str, SkillEntry] = {}
    for name, spec in (raw.get("skills") or {}).items():
        spec = spec or {}
        out[name] = SkillEntry(
            name=name,
            mode=spec.get("mode", "reference"),
            tools=tuple(spec.get("tools", []) or []),
            source=spec.get("source"),
            ref=spec.get("ref"),
            sub_path=spec.get("sub_path"),
            layout=spec.get("layout"),
            post_install=tuple(spec.get("post_install", []) or []),
            secrets_env=tuple(spec.get("secrets_env", []) or []),
            patches=tuple(spec.get("patches", []) or []),
        )
    return out


# --------------------------------------------------------------------------- helpers


def _run(argv: list[str], cwd: Path | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(argv, cwd=cwd, capture_output=True, text=True, check=False)


def _cache_dir(source: str) -> Path:
    """Cache location for a sub-path/multi-layout source clone."""
    digest = hashlib.sha1(source.encode()).hexdigest()[:16]
    return Path.home() / ".cache" / "egzakta-org" / "skills" / digest


def _post_install_fingerprint(entry: SkillEntry) -> str:
    """Stable fingerprint of the post_install command list."""
    raw = "\n".join(entry.post_install).encode()
    return hashlib.sha1(raw).hexdigest()[:12]


def _vendor_source(plat: Path, entry: SkillEntry) -> Path:
    """Resolve the source dir for a vendor-mode skill."""
    return plat / "skills" / "vendor" / entry.name


def _vendor_fingerprint(plat: Path, entry: SkillEntry) -> str:
    """Content hash of every file under the vendor source dir.

    Walks the source deterministically (sorted), hashes each relative path + bytes.
    A platform-side edit (any character in any file) flips the fingerprint, which
    the stamp comparison picks up as DRIFT → triggers a re-copy.
    """
    src = _vendor_source(plat, entry)
    if not src.is_dir():
        return "missing"
    h = hashlib.sha1()
    for path in sorted(src.rglob("*")):
        if not path.is_file():
            continue
        # Skip the same things _copy_tree skips so the hash matches what we install.
        rel_parts = path.relative_to(src).parts
        if any(part in _EXCLUDE for part in rel_parts):
            continue
        h.update(path.relative_to(src).as_posix().encode())
        h.update(b"\x00")
        h.update(path.read_bytes())
        h.update(b"\x00")
    return h.hexdigest()[:12]


def _patch_path(plat: Path, rel: str) -> Path:
    """Resolve a patch path from the registry (relative to `platform/skills/patches/`)."""
    return plat / "skills" / "patches" / rel


def _patches_fingerprint(entry: SkillEntry, plat: Path) -> str:
    """Stable fingerprint of the patches list + each patch file's content.

    Changes to any patch file or to the list/order of patches flips the fingerprint,
    which the stamp comparison picks up as DRIFT → triggers a re-apply.
    """
    parts: list[str] = []
    for rel in entry.patches:
        path = _patch_path(plat, rel)
        sha = hashlib.sha1(path.read_bytes()).hexdigest()[:12] if path.is_file() else "missing"
        parts.append(f"{rel}:{sha}")
    raw = "\n".join(parts).encode()
    return hashlib.sha1(raw).hexdigest()[:12]


def _expected_stamp(entry: SkillEntry, head: str, plat: Path) -> str:
    """Render the stamp content for `entry`. For reference mode, `head` is the
    resolved upstream ref sha (the parent of any applied patches), NOT the current
    branch HEAD. For vendor mode, `head` is the content fingerprint of the source dir.
    """
    return (
        f"mode={entry.mode}\n"
        f"source={entry.source or ''}\n"
        f"ref={entry.ref or ''}\n"
        f"sub_path={entry.sub_path or ''}\n"
        f"layout={entry.layout or ''}\n"
        f"head={head}\n"
        f"post_install={_post_install_fingerprint(entry)}\n"
        f"patches={_patches_fingerprint(entry, plat)}\n"
        f"vendor_fp={_vendor_fingerprint(plat, entry) if entry.mode == 'vendor' else ''}\n"
    )


def _read_stamp(dest: Path) -> dict[str, str] | None:
    f = dest / _STAMP_NAME
    if not f.is_file():
        return None
    return dict(line.split("=", 1) for line in f.read_text(encoding="utf-8").splitlines() if "=" in line)


def _ensure_stamp_excluded(dest: Path) -> None:
    """Append _STAMP_NAME to `<dest>/.git/info/exclude` so it never shows up as
    'untracked' in the user's git status — for direct-clone destinations only.

    This is a per-clone, untracked exclude (not .gitignore); we never modify files
    that get committed back upstream.
    """
    info_dir = dest / ".git" / "info"
    if not info_dir.is_dir():
        return
    exclude_file = info_dir / "exclude"
    existing = exclude_file.read_text(encoding="utf-8") if exclude_file.is_file() else ""
    if any(line.strip() == _STAMP_NAME for line in existing.splitlines()):
        return
    suffix = "" if existing.endswith("\n") or not existing else "\n"
    exclude_file.write_text(f"{existing}{suffix}{_STAMP_NAME}\n", encoding="utf-8")


def _copy_tree(src: Path, dst: Path) -> None:
    """Mirror src → dst (deletes dst first to ensure mirror semantics); skips _EXCLUDE."""
    if dst.exists():
        shutil.rmtree(dst)
    shutil.copytree(src, dst, ignore=shutil.ignore_patterns(*_EXCLUDE))


# ------------------------------------------------------------------ cache management


def _ensure_cache(entry: SkillEntry) -> tuple[Path, str]:
    """Clone or fast-forward the source into the cache; return (path, HEAD sha)."""
    if not entry.source:
        raise ValueError(f"skill {entry.name}: reference mode requires `source`")
    cache = _cache_dir(entry.source)
    ref = entry.ref or "HEAD"
    if not (cache / ".git").exists():
        cache.parent.mkdir(parents=True, exist_ok=True)
        if cache.exists():
            shutil.rmtree(cache)
        proc = _run(["git", "clone", *_LF_CLONE_CONFIG, "--depth", "1", "--branch", ref, entry.source, str(cache)])
        if proc.returncode != 0:
            # Fall back to a full clone (some refs aren't reachable from a depth-1 shallow).
            if cache.exists():
                shutil.rmtree(cache)
            proc = _run(["git", "clone", *_LF_CLONE_CONFIG, entry.source, str(cache)])
            if proc.returncode != 0:
                raise RuntimeError(f"clone failed for {entry.source}: {proc.stderr.strip()}")
            proc = _run(["git", "checkout", ref], cwd=cache)
            if proc.returncode != 0:
                raise RuntimeError(f"checkout {ref} failed in {cache}: {proc.stderr.strip()}")
    else:
        _run(["git", "fetch", "--tags", "origin"], cwd=cache)
        proc = _run(["git", "checkout", ref], cwd=cache)
        if proc.returncode != 0:
            raise RuntimeError(f"checkout {ref} failed in {cache}: {proc.stderr.strip()}")
    head = _run(["git", "rev-parse", "HEAD"], cwd=cache).stdout.strip()
    return cache, head


# ---------------------------------------------------------------- install / check


def _run_post_install(entry: SkillEntry, dest: Path, console: Console) -> None:
    for cmd in entry.post_install:
        console.print(f"    [dim]$[/] {cmd}")
        if os.name == "nt":
            # Windows: npm/npx ship as `.cmd` shims CreateProcess can't launch from argv (WinError 2); the shell resolves them via PATHEXT. Commands are registry-controlled, not user input.
            proc = subprocess.run(cmd, cwd=dest, capture_output=True, text=True, check=False, shell=True)
        else:
            proc = _run(shlex.split(cmd), cwd=dest)
        if proc.returncode != 0:
            raise RuntimeError(f"post_install `{cmd}` failed in {dest}: {proc.stderr.strip()}")


def _apply_patches(entry: SkillEntry, dest: Path, plat: Path, console: Console) -> None:
    """Reset the org-managed branch onto the current HEAD and apply each patch as a
    committed change. Assumes the caller has already checked out the upstream ref.

    Each apply is verified with `git apply --check` first so we fail fast (before any
    state change) when upstream has shifted the lines a patch touches. The commit is
    made with engine-owned author metadata so it never gets confused with the user's
    commits and never picks up their git identity.
    """
    if not entry.patches:
        return
    # Recreate the managed branch from the current upstream HEAD.
    _run(["git", "branch", "-D", _MANAGED_BRANCH], cwd=dest)  # ignore if absent
    proc = _run(["git", "checkout", "-b", _MANAGED_BRANCH], cwd=dest)
    if proc.returncode != 0:
        raise RuntimeError(f"failed to create {_MANAGED_BRANCH}: {proc.stderr.strip()}")
    for rel in entry.patches:
        patch = _patch_path(plat, rel)
        if not patch.is_file():
            raise RuntimeError(f"patch not found: platform/skills/patches/{rel}")
        # Dry-run apply first: surface a clean error before mutating anything.
        check = _run(["git", "apply", "--check", str(patch)], cwd=dest)
        if check.returncode != 0:
            raise RuntimeError(
                f"patch {rel} does not apply to {entry.source}@{entry.ref or 'HEAD'}; "
                f"rebase platform/skills/patches/{rel} against the current upstream and re-run.\n"
                f"  git apply --check stderr: {check.stderr.strip()}"
            )
        console.print(f"    [dim]apply[/] patches/{rel}")
        proc = _run(["git", "apply", "--index", str(patch)], cwd=dest)
        if proc.returncode != 0:
            raise RuntimeError(f"patch {rel} apply failed mid-flight: {proc.stderr.strip()}")
    # Skip commit if patches happened to be no-ops against this ref.
    if _run(["git", "diff", "--cached", "--quiet"], cwd=dest).returncode == 0:
        return
    msg = f"[org-install] apply {len(entry.patches)} patch(es): {', '.join(entry.patches)}"
    proc = _run(
        ["git", "-c", f"user.name={_COMMIT_USER}", "-c", f"user.email={_COMMIT_EMAIL}", "commit", "-m", msg],
        cwd=dest,
    )
    if proc.returncode != 0:
        raise RuntimeError(f"failed to commit applied patches: {proc.stderr.strip()}")


def _install_direct(entry: SkillEntry, dest: Path, plat: Path, console: Console) -> str:
    """Clone (or fetch+checkout) the source into the destination, then apply patches
    on a local managed branch if any are declared. Returns the resolved upstream ref
    sha (the parent of applied patches, NOT the current branch HEAD).
    """
    ref = entry.ref or "HEAD"
    dest.parent.mkdir(parents=True, exist_ok=True)
    if (dest / ".git").exists():
        # Refuse to clobber a clone of a different upstream.
        existing = _run(["git", "remote", "get-url", "origin"], cwd=dest).stdout.strip()
        if entry.source and existing and existing != entry.source:
            raise RuntimeError(
                f"{dest} has remote {existing!r}; expected {entry.source!r}. "
                "Move it aside and re-run."
            )
        # Filter the stamp file out of the local-edits gate (it's intentionally untracked).
        # If the managed branch is currently checked out, switch detached first so we can
        # safely reset it onto the new ref further down. We still refuse to proceed if the
        # user has uncommitted edits on top of either branch.
        porcelain = _run(["git", "status", "--porcelain"], cwd=dest).stdout
        unmanaged = [
            line for line in porcelain.splitlines()
            if line.strip() and not line.endswith(f" {_STAMP_NAME}")
        ]
        if unmanaged:
            raise RuntimeError(
                f"{len(unmanaged)} uncommitted local edit(s) in {dest}; refusing to overwrite. "
                f"Stash, commit, or `git checkout -- .` to discard, then re-run."
            )
        _run(["git", "fetch", "--tags", "origin"], cwd=dest)
        # Detach onto the ref so we can drop+recreate org-managed cleanly.
        proc = _run(["git", "checkout", "--detach", ref], cwd=dest)
        if proc.returncode != 0:
            # `--detach` against a tag is the same as a plain checkout; if for some reason
            # that fails (e.g. ref is invalid), fall back to a plain checkout for the error.
            proc = _run(["git", "checkout", ref], cwd=dest)
            if proc.returncode != 0:
                raise RuntimeError(f"checkout {ref} failed in {dest}: {proc.stderr.strip()}")
    else:
        if dest.exists():
            raise RuntimeError(
                f"{dest} exists but is not a git clone. Move or remove it manually, then re-run."
            )
        if not entry.source:
            raise ValueError(f"skill {entry.name}: reference mode requires `source`")
        proc = _run(["git", "clone", *_LF_CLONE_CONFIG, "--branch", ref, entry.source, str(dest)])
        if proc.returncode != 0:
            # Some refs (commit shas) can't be cloned with --branch; fall back.
            proc = _run(["git", "clone", *_LF_CLONE_CONFIG, entry.source, str(dest)])
            if proc.returncode != 0:
                raise RuntimeError(f"clone failed for {entry.source}: {proc.stderr.strip()}")
            proc = _run(["git", "checkout", ref], cwd=dest)
            if proc.returncode != 0:
                raise RuntimeError(f"checkout {ref} failed in {dest}: {proc.stderr.strip()}")
    # The resolved ref sha is the parent of any patches; record it before applying.
    head_at_ref = _run(["git", "rev-parse", "HEAD"], cwd=dest).stdout.strip()
    _apply_patches(entry, dest, plat, console)
    _run_post_install(entry, dest, console)
    return head_at_ref


def _install_subpath(entry: SkillEntry, dest: Path, console: Console) -> str:
    """Clone to cache, then copy the sub_path into dest."""
    cache, head = _ensure_cache(entry)
    if not entry.sub_path:
        raise ValueError(f"skill {entry.name}: _install_subpath requires sub_path")
    src = cache / entry.sub_path
    if not src.is_dir():
        raise RuntimeError(f"sub_path {entry.sub_path!r} not found in {cache}")
    dest.parent.mkdir(parents=True, exist_ok=True)
    _copy_tree(src, dest)
    _run_post_install(entry, dest, console)
    return head


def _render_tool_blocks_in_dest(dest: Path, tool: str) -> None:
    """Resolve `<!-- tool:… -->` conditional blocks in every Markdown file under dest.

    Vendor skills are copied byte-for-byte, then each `*.md` is post-processed so a
    single shared source can carry tool-specific sections (e.g. a Droid-only "Task
    tool" path). The fingerprint recorded in the stamp hashes the SOURCE dir, not the
    rendered dest, so drift detection is unaffected by this per-tool divergence.
    """
    for path in dest.rglob("*.md"):
        original = path.read_text(encoding="utf-8")
        rendered = render_tool_blocks(original, tool)
        if rendered != original:
            path.write_text(rendered, encoding="utf-8")


def _install_vendor(entry: SkillEntry, dest: Path, plat: Path, tool: str, console: Console) -> str:
    """Copy `platform/skills/vendor/<name>/` into dest. Returns the content fingerprint
    of the source dir, which is what `head` records in the stamp for vendor mode."""
    src = _vendor_source(plat, entry)
    if not src.is_dir():
        raise RuntimeError(
            f"skill {entry.name}: vendor mode requires platform/skills/vendor/{entry.name}/ to exist"
        )
    dest.parent.mkdir(parents=True, exist_ok=True)
    _copy_tree(src, dest)
    _render_tool_blocks_in_dest(dest, tool)
    _run_post_install(entry, dest, console)
    return _vendor_fingerprint(plat, entry)


def _install_one(entry: SkillEntry, dest: Path, plat: Path, tool: str, console: Console) -> str:
    """Dispatch on mode/layout; return resolved upstream ref sha (parent of any
    patches) for reference mode, or the source content fingerprint for vendor mode.
    """
    if entry.mode == "vendor":
        if entry.patches:
            raise NotImplementedError(
                f"skill {entry.name}: patches are reference-mode only (vendor sources are "
                "edited in-place under platform/skills/vendor/)"
            )
        return _install_vendor(entry, dest, plat, tool, console)
    if entry.mode != "reference":
        raise ValueError(f"skill {entry.name}: unknown mode {entry.mode!r}")
    if entry.layout == "multi":
        raise NotImplementedError("layout: multi not yet supported (use a single sub_path)")
    if entry.sub_path:
        if entry.patches:
            raise NotImplementedError(
                f"skill {entry.name}: patches are only supported for direct-clone reference mode "
                "(not sub_path / multi)."
            )
        return _install_subpath(entry, dest, console)
    return _install_direct(entry, dest, plat, console)


def _check_state(action: SkillAction, plat: Path) -> tuple[bool, str]:
    """Return (drift, reason) for the destination without mutating anything."""
    dest = action.dest
    entry = action.entry
    if not dest.exists():
        return True, "missing"
    stamp = _read_stamp(dest)
    if stamp is None:
        return True, "no install stamp (unmanaged dir)"
    expected = _expected_stamp(entry, head=stamp.get("head", ""), plat=plat)
    expected_keys = {line.split("=", 1)[0]: line for line in expected.strip().split("\n")}
    for key, line in expected_keys.items():
        if key == "head":
            continue  # head is informational; verified against ref below for direct clones
        actual_line = f"{key}={stamp.get(key, '')}"
        if actual_line != line:
            return True, f"stamp mismatch ({key})"
    # Vendor mode: the stamp's `head` IS the source fingerprint. If the source on disk
    # has been edited since install, the recomputed fingerprint won't match → DRIFT.
    if entry.mode == "vendor":
        wanted_fp = _vendor_fingerprint(plat, entry)
        if stamp.get("head") != wanted_fp:
            return True, f"vendor source changed (stamp head={stamp.get('head', '')[:8]}, want {wanted_fp[:8]})"
        return False, "ok"
    if entry.mode == "reference" and not entry.sub_path and entry.layout != "multi":
        if (dest / ".git").exists():
            # With patches: HEAD should be `len(patches)` commits ahead of the ref.
            # Without patches: HEAD should equal the ref directly.
            n_patches = len(entry.patches)
            head_ref = f"HEAD~{n_patches}" if n_patches else "HEAD"
            actual_parent = _run(["git", "rev-parse", head_ref], cwd=dest).stdout.strip()
            wanted = _run(["git", "rev-parse", entry.ref or "HEAD"], cwd=dest).stdout.strip()
            if wanted and actual_parent != wanted:
                return True, (
                    f"ref mismatch ({head_ref}={actual_parent[:8]}, want {entry.ref})"
                )
            if n_patches:
                # Verify the managed branch is the one actually checked out — protects
                # against a user who manually moved HEAD elsewhere.
                branch = _run(["git", "rev-parse", "--abbrev-ref", "HEAD"], cwd=dest).stdout.strip()
                if branch != _MANAGED_BRANCH:
                    return True, f"on branch {branch!r}, expected {_MANAGED_BRANCH!r}"
            porcelain = _run(["git", "status", "--porcelain"], cwd=dest).stdout
            unmanaged = [
                line for line in porcelain.splitlines()
                if line.strip() and not line.endswith(f" {_STAMP_NAME}")
            ]
            if unmanaged:
                return True, "local edits in dest"
    return False, "ok"


def _describe(action: SkillAction) -> str:
    e = action.entry
    if e.mode == "vendor":
        return f"vendor copy from platform/skills/vendor/{e.name}/ → {action.dest}"
    base = f"{e.source}@{e.ref or 'HEAD'}"
    patches = f" + apply {len(e.patches)} patch(es)" if e.patches else ""
    if e.layout == "multi":
        return f"clone {base} → cache → install each skills/* into {action.dest.parent}{patches}"
    if e.sub_path:
        return f"clone {base} → cache → copy {e.sub_path}/ → {action.dest}{patches}"
    extra = f" + post_install: {', '.join(e.post_install)}" if e.post_install else ""
    return f"clone {base} → {action.dest}{patches}{extra}"


def process(
    action: SkillAction,
    plat: Path,
    *,
    check: bool,
    dry_run: bool,
    console: Console,
) -> SkillResult:
    """Run check / dry-run / install for one SkillAction."""
    if check:
        drift, reason = _check_state(action, plat)
        return SkillResult(status="DRIFT" if drift else "OK", detail=reason, secrets=action.entry.secrets_env)
    if dry_run:
        return SkillResult(status="WOULD", detail=_describe(action), secrets=action.entry.secrets_env)
    try:
        head = _install_one(action.entry, action.dest, plat, action.tool, console)
    except Exception as exc:  # surface as ERROR; install.py decides how to aggregate
        return SkillResult(status="ERROR", detail=str(exc), secrets=action.entry.secrets_env)
    (action.dest / _STAMP_NAME).write_text(_expected_stamp(action.entry, head, plat), encoding="utf-8")
    _ensure_stamp_excluded(action.dest)
    return SkillResult(status="INSTALLED", detail=f"head={head[:8]}", secrets=action.entry.secrets_env)


# ------------------------------------------------------------------ action building


def build_actions(
    plat: Path,
    registry: dict[str, SkillEntry],
    profiles: dict[str, "object"],  # imported lazily to avoid a circular dep
    *,
    is_global: bool,
    global_skills: tuple[str, ...],
    repos_with_skills: list[tuple[str, Path, tuple[str, ...]]],
    tools_filter: list[str] | None,
) -> tuple[list[SkillAction], list[str]]:
    """Build the full set of SkillActions for the requested scope.

    `repos_with_skills`: list of (repo_name, repo_dir, repo_skills) — only repos
    actually present on disk with a non-empty `skills:` list. Used only when
    is_global is False (or both, if the caller wanted to mix).

    Returns (actions, warnings). Warnings cover misconfigurations (unknown skills,
    skills referenced for a tool that doesn't support them, etc.).
    """
    _ = plat  # reserved for future vendor-mode source lookups
    actions: list[SkillAction] = []
    warnings: list[str] = []

    def _resolve_skill(name: str) -> SkillEntry | None:
        if name not in registry:
            warnings.append(f"skill {name!r} is not in platform/skills/index.yaml — skipped")
            return None
        return registry[name]

    target_tools = lambda entry: [
        t for t in entry.tools if (tools_filter is None or t in tools_filter)
    ]

    if is_global:
        for name in global_skills:
            entry = _resolve_skill(name)
            if entry is None:
                continue
            for tool in target_tools(entry):
                profile = profiles.get(tool)
                base = getattr(profile, "skills_global_dir", None) if profile else None
                if not base:
                    warnings.append(f"{tool} has no skills_global path — {name} skipped for {tool}")
                    continue
                dest = Path(base).expanduser() / name
                actions.append(SkillAction(skill=name, tool=tool, scope="global", dest=dest, entry=entry))
    else:
        for repo_name, repo_dir, repo_skills in repos_with_skills:
            for name in repo_skills:
                entry = _resolve_skill(name)
                if entry is None:
                    continue
                for tool in target_tools(entry):
                    profile = profiles.get(tool)
                    base = getattr(profile, "skills_project_dir", None) if profile else None
                    if not base:
                        warnings.append(
                            f"{tool} has no skills_project path — {name} skipped for {repo_name}/{tool}"
                        )
                        continue
                    dest = (repo_dir / base).expanduser() / name
                    actions.append(
                        SkillAction(
                            skill=name, tool=tool, scope="project", dest=dest, entry=entry, repo=repo_name
                        )
                    )

    return actions, warnings
